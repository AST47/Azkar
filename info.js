(function renderSharedInfo(){
  const aboutEl = document.getElementById('infoAbout');
  if (aboutEl) aboutEl.innerHTML = INFO_ABOUT_HTML;

  const logEl = document.getElementById('infoChangelog');
  if (logEl) {
    logEl.innerHTML = '<h3 style="margin-top:22px;">سجل الإصدارات</h3><div class="changelog"></div>';
    const box = logEl.querySelector('.changelog');
    CHANGELOG.forEach(([ver, text]) => {
      const row = document.createElement('div');
      row.className = 'changelog-row';
      const v = document.createElement('span');
      v.className = 'changelog-version';
      v.textContent = ver;
      const t = document.createElement('span');
      t.textContent = text;
      row.append(v, t);
      box.appendChild(row);
    });
  }
})();
